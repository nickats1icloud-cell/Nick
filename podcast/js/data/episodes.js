/** Τα επεισόδια ταξινομημένα από το νεότερο στο παλαιότερο. */
export const EPISODES_SORTED = [...EPISODES].sort(
  (a, b) => new Date(b.date) - new Date(a.date)
);

/** Όλα τα tags που εμφανίζονται, με πλήθος επεισοδίων. */
export function allTags() {
  const counts = new Map();
  for (const ep of EPISODES) {
    for (const tag of ep.tags) counts.set(tag, (counts.get(tag) || 0) + 1);
  }
  return [...counts.entries()]
    .sort((a, b) => b[1] - a[1])
    .map(([tag, count]) => ({ tag, count }));
}

export function getEpisode(id) {
  return EPISODES.find((ep) => ep.id === id) || null;
}

export function latestEpisode() {
  return EPISODES_SORTED[0];
}
